#!/usr/bin/env node
/*
 * Regenerates docs/vectors.js from tests/tto_calc_test_vectors_v1.1.json so that the calculator's
 * Verification tab works offline, including from file://, without fetching the JSON.
 * Usage: node tests/build_vectors_js.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const src = path.join(__dirname, 'tto_calc_test_vectors_v1.1.json');
const dst = path.join(__dirname, '..', 'docs', 'vectors.js');
const text = fs.readFileSync(src, 'utf8');
const data = JSON.parse(text);                       // validate before writing
const body = '/* Generated by tests/build_vectors_js.js from tests/tto_calc_test_vectors_v1.1.json. Do not edit by hand. */\n' +
  '(function (root, data) {\n' +
  "  if (typeof module === 'object' && module.exports) { module.exports = data; } else { root.TTO_VECTORS = data; }\n" +
  "}(typeof self !== 'undefined' ? self : this, " + JSON.stringify(data, null, 1) + '));\n';
fs.writeFileSync(dst, body, 'utf8');
console.log('Wrote ' + dst + ' (' + data.vectors.length + ' vectors, ' + data.spec + ').');
